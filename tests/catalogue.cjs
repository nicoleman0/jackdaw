const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

const html = fs.readFileSync('catalogue.html', 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
function element(key, type = 'range') {
  return { dataset: key ? { key } : {}, type, style: { setProperty(name, value) { this[name] = value; }, removeProperty(name) { delete this[name]; } }, value: '', addEventListener(name, handler) { this[name] = handler; } };
}
const controls = ['ground', 'paper', 'ultra', 'lime', 'ink', 'muted', 'spacing', 'radius', 'body', 'width'].map(key => element(key, ['ground', 'paper', 'ultra', 'lime', 'ink', 'muted'].includes(key) ? 'color' : 'range'));
const outputs = ['spacing', 'radius', 'body', 'width'].map(key => ({ dataset: { output: key } }));
const ids = Object.fromEntries(['preview', 'frame', 'prompt', 'preset', 'inks', 'stock', 'reset', 'copy', 'copy-status'].map(id => [id, element()]));
const document = { querySelector(selector) { return ids[selector.slice(1)]; }, querySelectorAll(selector) { return selector === '[data-key]' ? controls : outputs; } };
const classes = new Set(['jd-scope']);
ids.preview.classList = { add: name => classes.add(name), remove: name => classes.delete(name), [Symbol.iterator]: () => classes[Symbol.iterator]() };
Object.defineProperty(ids.preview.classList, 'length', { get: () => classes.size });
// Stands in for the browser reading the preset classes in inks.css; picker overrides win, as inline styles do.
const rootValues = { '--jd-ink-print': '#2f17f0', '--jd-ink-accent': '#c4f01c', '--jd-ground': '#eef0f9', '--jd-paper': '#ffffff' };
const presetValues = { 'jd-inks-federal': { '--jd-ink-print': '#3d5588', '--jd-ink-accent': '#ff6c2f' }, 'jd-stock-cream': { '--jd-ground': '#f5eedc', '--jd-paper': '#fffaef' } };
const getComputedStyle = el => ({ getPropertyValue(name) { const fromClass = [...classes].map(c => presetValues[c]?.[name]).find(Boolean); return ' ' + (el.style[name] ?? fromClass ?? rootValues[name]); } });
vm.runInNewContext(script, { document, getComputedStyle, navigator: { clipboard: { writeText: async () => {} } } });
assert.match(ids.prompt.value, /Body size: 17px/);
const spacing = controls.find(control => control.dataset.key === 'spacing');
spacing.value = '1.25'; spacing.input();
assert.equal(ids.preview.style['--jd-s-2'], '1.25rem');
assert.match(ids.prompt.value, /Spacing: 1.25×/);
const width = controls.find(control => control.dataset.key === 'width');
width.value = '800'; width.input();
assert.match(ids.prompt.value, /Preview width: 800px/);
ids.preset.change({ target: { value: 'warm' } });
assert.equal(ids.preview.style['--jd-ground'], '#f4f0e7');
assert.match(ids.prompt.value, /Ground: #f4f0e7/);
ids.reset.click();
assert.equal(ids.preview.style['--jd-ground'], '#eef0f9');
assert.match(ids.prompt.value, /Ground: #eef0f9/);
ids.inks.change({ target: { value: 'federal' } });
assert.ok(classes.has('jd-inks-federal') && classes.has('jd-scope'));
assert.equal(ids.preview.style['--jd-ink-print'], '#3d5588');
assert.equal(ids.preview.style['--jd-ink-accent'], '#ff6c2f');
assert.equal(ids.preview.style['--jd-ground'], '#eef0f9', 'an ink pair leaves the stock alone');
assert.match(ids.prompt.value, /Ink pair: federal/);
const ultra = controls.find(control => control.dataset.key === 'ultra');
ultra.value = '#123456'; ultra.input();
assert.equal(ids.preview.style['--jd-ink-print'], '#123456', 'a picker overrides the pair');
ids.stock.change({ target: { value: 'cream' } });
assert.ok(classes.has('jd-stock-cream') && classes.has('jd-inks-federal'));
assert.equal(ids.preview.style['--jd-ground'], '#f5eedc');
assert.equal(ids.preview.style['--jd-ink-print'], '#123456', 'a stock keeps the picked ink');
assert.match(ids.prompt.value, /Paper stock: cream/);
ids.inks.change({ target: { value: '' } });
assert.ok(!classes.has('jd-inks-federal'));
assert.equal(ids.preview.style['--jd-ink-print'], '#2f17f0', 'clearing the pair restores the default inks');
ids.reset.click();
assert.ok(!classes.has('jd-stock-cream') && classes.has('jd-scope'));
assert.equal(ids.preview.style['--jd-ink-print'], '#2f17f0');
assert.equal(ids.stock.value, '');
console.log('Catalogue controls, ink pairs, stocks and reset passed');
